export function getDailyConnectionsPuzzle(dateStr: string): DailyConnectionsPuzzle {
  const match = CONNECTIONS_PUZZLES.find((p) => p.date === dateStr);
  if (match) return match;
  // Fallback déterministe
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
  }
  const index = Math.abs(hash) % CONNECTIONS_PUZZLES.length;
  return {
    ...CONNECTIONS_PUZZLES[index],
    date: dateStr,
  };
}
